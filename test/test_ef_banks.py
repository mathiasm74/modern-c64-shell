"""The five banks, served from the EasyFlash cart (PLAN.md section 7, phase 3).

Needs a drive, so it is its own module. The bank images here are the One ROM
ones relinked: same C, same shared asm, only crt0_*.s reassembled with
-D EF_BANK=1 to pick the relocated RAM window and the $9Fxx entry points
(build/ef/cfg/*.cfg, generated by tools/make_ef_bank_cfg.py).

WHY THIS MODULE EARNS ITS RUNTIME: on the One ROM build a served bank is
inert in VICE -- bank_call falls back to running the image out of the RAM under
$A000, so the suite exercises a stand-in, and the real serving path is
hardware-only. Here the cartridge banking IS emulated, so these run the actual
mechanism. `help` in particular covers the RODATA2 rule (a bank follows the
dispatch table's name pointers, so they must live in the always-mapped half) --
the one whose failure mode is structured garbage and which cannot be reproduced
in VICE on the other target at all.
"""

import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

_HERE = os.path.dirname(os.path.abspath(__file__))
_CRT = os.path.join(_HERE, "..", "build", "ef", "tardis.crt")
_STOCK_K = os.path.join(_HERE, "..", "stock-roms", "kernal.901227-03.bin")
_STOCK_B = os.path.join(_HERE, "..", "stock-roms", "basic.901226-01.bin")
_DISK = os.path.join(_HERE, "data", "test.d64")
_SCRATCH = os.path.join(_HERE, "data", "_scratch_ef.d64")
_HAVE = (os.path.exists(_CRT) and os.path.exists(_STOCK_K)
         and os.path.exists(_STOCK_B) and os.path.exists(_DISK))

if _HAVE:
    shutil.copyfile(_DISK, _SCRATCH)      # cp/rm mutate it; never the fixture


def _vice():
    sys.path.insert(0, os.path.join(_HERE, "lib"))
    from vice import Vice
    return Vice(kernal=_STOCK_K, basic=_STOCK_B, disk=_SCRATCH,
                extra_args=["-cartcrt", _CRT, "+easyflashjumper"])


def _boot(sv):
    for _ in range(60):
        sv.run_for(0.25)
        if "8: " in sv.screen_text() or "8>" in sv.screen_text():
            return
    raise AssertionError("no prompt:\n%s" % sv.screen_text())


def _type(sv, text):
    for chunk in [text[i:i + 9] for i in range(0, len(text), 9)]:
        sv.inject_keys(chunk)
        for _ in range(80):
            sv.run_for(0.1)
            if sv.read_byte(0xC6) == 0:
                break
    sv.run_for(2.5)


def _run(sv, cmd, want, tries=6):
    """Type a command and poll until `want` shows up."""
    _type(sv, "clear\r")
    _type(sv, cmd + "\r")
    for _ in range(tries):
        if want in sv.screen_text():
            return sv.screen_text()
        sv.run_for(1.0)
    raise AssertionError("%r: never saw %r\n%s" % (cmd, want, sv.screen_text()))


def test_ef_disk_bank_lists_and_reads(v):
    (void) = v
    if not _HAVE:
        print("      (skipped: no tardis.crt, stock ROMs or disk)")
        return
    with _vice() as sv:
        _boot(sv)
        # The boot-time identity fetch is itself a bank call, and it ran before
        # the first prompt: the drive's name is in the prompt.
        assert "1541" in sv.screen_text(), \
            "boot-time identify did not name the drive:\n%s" % sv.screen_text()
        _run(sv, "ls", "README")
        _run(sv, "pwd", "TEST DISK")
        _run(sv, "load prog", "loaded $2000")


def test_ef_files_bank_commands(v):
    (void) = v
    if not _HAVE:
        print("      (skipped: no tardis.crt, stock ROMs or disk)")
        return
    with _vice() as sv:
        _boot(sv)
        _run(sv, "status", "00 OK")
        _run(sv, "cat readme", "C64 SHELL TEST DISK")
        # help walks the dispatch table and follows its NAME pointers out of
        # the bank. On the One ROM build getting that wrong is hardware-only
        # (in VICE a bank runs from RAM, where both halves are readable); here
        # the bank really is served, so this is a genuine check.
        got = _run(sv, "help", "Commands:")
        for name in ("about", "border", "status", "ver"):
            assert name in got, "help lost %r:\n%s" % (name, got)


def test_ef_files_bank_writes_to_the_drive(v):
    """cp exercises CHKOUT + the deferred CHROUT, so it proves the routing.

    $FFD2 is the stock KERNAL's `jmp ($0326)`, and $0326 points at our own
    published entry $9FD2 -- chrout_route, which sends to the drive after a
    CHKOUT and to the screen otherwise. Pointing $0326 straight at the screen
    implementation instead would put a copied file on the display.
    """
    (void) = v
    if not _HAVE:
        print("      (skipped: no tardis.crt, stock ROMs or disk)")
        return
    with _vice() as sv:
        _boot(sv)
        _run(sv, "cp readme efcopy", "copied")
        _run(sv, "status", "00 OK")
        # rm reports "not found" when nothing matched, so a clean run is proof
        # the file was really created on the disk.
        _type(sv, "clear\r")
        _type(sv, "rm efcopy\r")
        assert "not found" not in sv.screen_text(), \
            "cp did not actually write the file:\n%s" % sv.screen_text()


def test_ef_editor_banks_open_a_file(v):
    (void) = v
    if not _HAVE:
        print("      (skipped: no tardis.crt, stock ROMs or disk)")
        return
    with _vice() as sv:
        _boot(sv)
        # The hex editor renders through svc 12 (scr_display), which lives in
        # ROML and is reached at $9FA4 -- the $FFA4 of this target.
        _run(sv, "hex readme", "0000 00 20 43")
        _type(sv, "\x18")                    # ^X; unmodified, so it just exits
        _type(sv, "n")
        _run(sv, "edit readme", "C64 SHELL TEST DISK")
